/// Logs the app process's peak memory footprint (the figure iOS uses for
/// memory limits) whenever it grows by 1 MB or more. For validation test 9.
enum MemorySampler {
    private static var peak: UInt64 = 0
    private static var lastLogged: UInt64 = 0
    private static let timer = DispatchSource.makeTimerSource(queue: DispatchQueue(label: "memory-sampler"))

    static func start() {
        timer.schedule(deadline: .now(), repeating: .milliseconds(20))
        timer.setEventHandler {
            var info = task_vm_info_data_t()
            var count = mach_msg_type_number_t(MemoryLayout<task_vm_info_data_t>.size / MemoryLayout<natural_t>.size)
            let result = withUnsafeMutablePointer(to: &info) {
                $0.withMemoryRebound(to: integer_t.self, capacity: Int(count)) {
                    task_info(mach_task_self_, task_flavor_t(TASK_VM_INFO), $0, &count)
                }
            }
            guard result == KERN_SUCCESS else { return }
            peak = max(peak, info.phys_footprint)
            if peak >= lastLogged + 1_048_576 {
                lastLogged = peak
                print(String(format: "SSMEM peak %.1f MB", Double(peak) / 1_048_576))
            }
        }
        timer.resume()
    }
}
